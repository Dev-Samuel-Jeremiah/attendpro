@register.simple_tag
def icon(name, size=None):
    s = f' width="{size}" height="{size}"' if size else ""
    return mark_safe(
        f'<svg viewBox="0 0 24 24"{s} fill="none" stroke="currentColor" stroke-width="2" '
        f'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">{_P.get(name, "")}</svg>')


@register.simple_tag
def avatar(user, cls=""):
    if getattr(user, "photo", None):
        return format_html('<span class="avatar {}"><img src="{}" alt=""></span>', cls, user.photo.url)
    return format_html('<span class="avatar {}">{}</span>', cls, user.initials)


@register.filter
def localtime_fmt(dt, fmt="%I:%M %p"):
    if not dt:
        return "—"
    return timezone.localtime(dt).strftime(fmt)


@register.simple_tag(takes_context=True)
def active(context, *names):
    match = getattr(context["request"], "resolver_match", None)
    return "active" if match and match.url_name in names else ""
